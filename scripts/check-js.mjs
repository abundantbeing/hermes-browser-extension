// The whole chain as one string, for the tests that check what it gates.
export const CHECK_JS = CHECK_JS_COMMANDS.join(' && ');

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  for (const command of CHECK_JS_COMMANDS) {
    try {
      execSync(command, { stdio: 'inherit' });
    } catch (error) {
      console.error(`check:js failed at: ${command}`);
      process.exit(typeof error?.status === 'number' && error.status ? error.status : 1);
    }
  }
}
