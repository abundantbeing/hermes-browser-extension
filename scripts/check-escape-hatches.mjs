// Deterministic gate for inline escape hatches (ESLint silences, TypeScript checkpoint
// pragmas, and work-item markers in comments). New occurrences fail unless explicitly
// stale baseline rows fail so the list only shrinks. Vendored and generated trees are excluded.
//
// Usage:
//   node scripts/check-escape-hatches.mjs
//   node scripts/check-escape-hatches.mjs --update-baseline   # drop stale rows only
//
// Environment overrides (tests only):
//   HERMES_ESCAPE_HATCHES_ROOT
//   HERMES_ESCAPE_HATCHES_BASELINE

import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import * as espree from 'espree';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const defaultRoot = path.resolve(scriptDir, '..');
const defaultBaselinePath = path.join(scriptDir, 'escape-hatch-baseline.json');

export const PATTERN_ORDER = Object.freeze([
  'eslint-disable',
  'ts-nocheck',
  'ts-ignore',
  'ts-expect-error',
  'TODO',
  'FIXME',
  'HACK',
  'XXX',
]);

const PATTERN_REGEX = Object.freeze({
  'eslint-disable': /eslint-disable(?:-next-line|-line)?/,
  'ts-nocheck': /@ts-nocheck\b/,
  'ts-ignore': /@ts-ignore\b/,
  'ts-expect-error': /@ts-expect-error\b/,
  TODO: /\bTODO\b/,
  FIXME: /\bFIXME\b/,
  HACK: /\bHACK\b/,
  XXX: /\bXXX\b/,
});

/** @type {ReadonlyArray<{ reason: string, test: (relative: string) => boolean }>} */
export const FILE_EXCLUSIONS = Object.freeze([
  {
    reason: 'npm lockfile (integrity strings can contain XXX-like substrings)',
    test: (relative) => /(?:^|\/)(?:package-lock|npm-shrinkwrap)\.json$/.test(relative),
  },
  {
    reason: 'third-party vendor copies (vendor:security)',
    test: (relative) => relative.startsWith('extension/lib/vendor/'),
  },
  {
    reason: 'generated by scripts/sync-hermes-context-windows.mjs',
    test: (relative) => relative === 'extension/lib/hermes-context-registry-data.mjs',
  },
  {
    reason: 'generated by scripts/build-page-context-guard.mjs',
    test: (relative) => relative === 'extension/page-context-install-guard.js',
  },
]);

/** @type {ReadonlyArray<{ reason: string, name: string }>} */
export const SKIPPED_DIRECTORY_NAMES = Object.freeze([
  { name: 'node_modules', reason: 'dependencies' },
  { name: 'dist', reason: 'build output (build:*)' },
  { name: 'artifacts', reason: 'packaging/signing output' },
  { name: 'vendor', reason: 'nested vendor trees' },
  { name: '.git', reason: 'git metadata' },
]);

export const SCANNABLE_EXTENSIONS = new Set([
  '.js',
  '.mjs',
  '.cjs',
  '.ts',
  '.tsx',
  '.jsx',
  '.css',
  '.html',
  '.py',
]);

export const DEFAULT_SCAN_ROOTS = Object.freeze([
  'extension',
  'scripts',
  'tests',
]);

export const ROOT_CONFIG_FILES = Object.freeze([
  'eslint.config.js',
  'manifest.json',
  'package.json',
]);

const HELP_MESSAGE = [
  'Escape-hatch check failed.',
  'Fix the code instead of adding an inline hatch, or add a file-level eslint rule with an explicit reason in eslint.config.js.',
  'To shrink the baseline after removing hatches: node scripts/check-escape-hatches.mjs --update-baseline',
  'New baseline rows must be hand-edited into scripts/escape-hatch-baseline.json (never via --update-baseline).',
].join('\n');

function normalizeCommentText(text) {
  return text.replace(/\s+/g, ' ').trim();
}

export function baselineEntryKey(relativeFile, pattern, commentText) {
  const normalized = normalizeCommentText(commentText);
  return createHash('sha256')
    .update(`${relativeFile}\0${pattern}\0${normalized}`)
    .digest('hex')
    .slice(0, 16);
}

function espreeCommentText(comment) {
  return comment.type === 'Line' ? `//${comment.value}` : `/*${comment.value}*/`;
}

function espreeOptionsForFile(relativeFile) {
  const ext = path.extname(relativeFile).toLowerCase();
  /** @type {import('espree').EspreeOptions} */
  const options = {
    ecmaVersion: 'latest',
    comment: true,
    range: true,
  };
  options.sourceType = ext === '.cjs' ? 'script' : 'module';
  if (ext === '.jsx' || ext === '.tsx') {
    options.ecmaFeatures = { jsx: true };
  }
  return options;
}

/** @returns {Array<{ start: number, end: number, text: string }>} */
function commentSpansFromEspree(relativeFile, source) {
  const ext = path.extname(relativeFile).toLowerCase();
  try {
    const ast = espree.parse(source, espreeOptionsForFile(relativeFile));
    const comments = ast.comments ?? [];
    return comments.map((comment) => ({
      start: comment.start,
      end: comment.end,
      text: espreeCommentText(comment),
    }));
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error);
    if (ext === '.ts' || ext === '.tsx') {
      throw new Error(
        `escape-hatch scan cannot parse ${relativeFile}: TypeScript-only syntax is not supported by the ECMAScript parser. ${message}`,
      );
    }
    throw new Error(`escape-hatch scan cannot parse ${relativeFile}: ${message}`);
  }
}

/** @returns {Generator<{ start: number, end: number, text: string }>} */
function* commentSpansFromCss(source) {
  let index = 0;
  const length = source.length;
  while (index < length) {
    const char = source[index];
    const next = source[index + 1];
    if (char === '/' && next === '*') {
      const start = index;
      index += 2;
      while (index < length - 1 && !(source[index] === '*' && source[index + 1] === '/')) index += 1;
      index = Math.min(length, index + 2);
      yield { start, end: index, text: source.slice(start, index) };
      continue;
    }
    if (char === '"' || char === "'") {
      const quote = char;
      index += 1;
      while (index < length) {
        if (source[index] === '\\') {
          index += 2;
          continue;
        }
        if (source[index] === quote) {
          index += 1;
          break;
        }
        index += 1;
      }
      continue;
    }
    index += 1;
  }
}

/** @returns {Generator<{ start: number, end: number, text: string }>} */
function* commentSpansFromPython(source) {
  let index = 0;
  const length = source.length;
  while (index < length) {
    const char = source[index];
    if (char === '#') {
      const start = index;
      while (index < length && source[index] !== '\n') index += 1;
      yield { start, end: index, text: source.slice(start, index) };
      continue;
    }
    if (char === '"' || char === "'") {
      const quote = char;
      const triple = source[index + 1] === quote && source[index + 2] === quote;
      if (triple) {
        index += 3;
        while (index < length) {
          if (source[index] === quote && source[index + 1] === quote && source[index + 2] === quote) {
            index += 3;
            break;
          }
          if (source[index] === '\\') index += 2;
          else index += 1;
        }
        continue;
      }
      index += 1;
      while (index < length) {
        if (source[index] === '\\') {
          index += 2;
          continue;
        }
        if (source[index] === quote) {
          index += 1;
          break;
        }
        index += 1;
      }
      continue;
    }
    index += 1;
  }
}

function scriptTypeAttributeFromOpenTag(openTag) {
  const quoted = openTag.match(/\btype\s*=\s*(['"])([^'"]*)\1/i);
  if (quoted) return quoted[2].trim();
  const unquoted = openTag.match(/\btype\s*=\s*([^\s"'`=<>]+)/i);
  if (unquoted) return unquoted[1].trim();
  return undefined;
}

const EXECUTABLE_SCRIPT_MIME_BASES = new Set([
  'text/javascript',
  'application/javascript',
  'application/ecmascript',
  'text/ecmascript',
  'text/jscript',
  'application/x-javascript',
  'text/x-javascript',
]);

/** @returns {null | 'inline.mjs' | 'inline.cjs'} */
function inlineScriptEspreeFileFromOpenTag(openTag) {
  const typeAttr = scriptTypeAttributeFromOpenTag(openTag);
  if (typeAttr === undefined || typeAttr === '') {
    return 'inline.cjs';
  }
  const base = typeAttr.toLowerCase().split(';', 1)[0].trim();
  if (base === 'module') return 'inline.mjs';
  if (EXECUTABLE_SCRIPT_MIME_BASES.has(base)) return 'inline.cjs';
  return null;
}

/** @returns {Generator<{ start: number, end: number, text: string }>} */
function* commentSpansFromHtml(source) {
  let index = 0;
  const length = source.length;
  while (index < length) {
    if (source.startsWith('<!--', index)) {
      const start = index;
      index += 4;
      while (index < length - 2 && !source.startsWith('-->', index)) index += 1;
      index = Math.min(length, index + 3);
      yield { start, end: index, text: source.slice(start, index) };
      continue;
    }
    const lower = source.slice(index, index + 7).toLowerCase();
    if (lower.startsWith('<script')) {
      const openEnd = source.indexOf('>', index);
      if (openEnd === -1) break;
      const openTag = source.slice(index, openEnd + 1);
      const bodyStart = openEnd + 1;
      const closeMatch = source.slice(bodyStart).toLowerCase().indexOf('</script>');
      if (closeMatch === -1) break;
      const bodyEnd = bodyStart + closeMatch;
      const body = source.slice(bodyStart, bodyEnd);
      const pseudoFile = inlineScriptEspreeFileFromOpenTag(openTag);
      if (pseudoFile && body.trim()) {
        for (const span of commentSpansFromEspree(pseudoFile, body)) {
          yield { start: bodyStart + span.start, end: bodyStart + span.end, text: span.text };
        }
      }
      index = bodyEnd + '</script>'.length;
      continue;
    }
    if (source.slice(index, index + 6).toLowerCase().startsWith('<style')) {
      const openEnd = source.indexOf('>', index);
      if (openEnd === -1) break;
      const bodyStart = openEnd + 1;
      const closeMatch = source.slice(bodyStart).toLowerCase().indexOf('</style>');
      if (closeMatch === -1) break;
      const bodyEnd = bodyStart + closeMatch;
      const body = source.slice(bodyStart, bodyEnd);
      for (const span of commentSpansFromCss(body)) {
        yield { start: bodyStart + span.start, end: bodyStart + span.end, text: span.text };
      }
      index = bodyEnd + '</style>'.length;
      continue;
    }
    index += 1;
  }
}

/** @returns {Iterable<{ start: number, end: number, text: string }>} */
export function commentSpansForFile(relativeFile, source) {
  const ext = path.extname(relativeFile).toLowerCase();
  if (ext === '.css') return commentSpansFromCss(source);
  if (ext === '.html') return commentSpansFromHtml(source);
  if (ext === '.py') return commentSpansFromPython(source);
  if (SCANNABLE_EXTENSIONS.has(ext)) return commentSpansFromEspree(relativeFile, source);
  return [];
}

function classifyPattern(commentText) {
  const patterns = [];
  for (const pattern of PATTERN_ORDER) {
    if (PATTERN_REGEX[pattern].test(commentText)) patterns.push(pattern);
  }
  return patterns;
}

export function findEscapeHatchesInFile(relativeFile, source) {
  /** @type {Array<{ file: string, pattern: string, key: string, comment: string }>} */
  const hits = [];
  const ordinal = new Map();
  for (const span of commentSpansForFile(relativeFile, source)) {
    const patterns = classifyPattern(span.text);
    for (const pattern of patterns) {
      const base = baselineEntryKey(relativeFile, pattern, span.text);
      const count = ordinal.get(base) ?? 0;
      ordinal.set(base, count + 1);
      const key = count === 0 ? base : `${base}:${count}`;
      hits.push({
        file: relativeFile,
        pattern,
        key,
        comment: normalizeCommentText(span.text),
      });
    }
  }
  return hits;
}

function shouldSkipRelative(relative) {
  const normalized = relative.split(path.sep).join('/');
  for (const rule of FILE_EXCLUSIONS) {
    if (rule.test(normalized)) return rule.reason;
  }
  return null;
}

function collectFiles(absoluteRoot, relativePrefix, out) {
  if (!fs.existsSync(absoluteRoot)) return;
  for (const entry of fs.readdirSync(absoluteRoot, { withFileTypes: true })) {
    if (SKIPPED_DIRECTORY_NAMES.some(({ name }) => name === entry.name)) continue;
    const absolute = path.join(absoluteRoot, entry.name);
    const relative = relativePrefix ? path.posix.join(relativePrefix, entry.name) : entry.name;
    if (entry.isDirectory()) {
      collectFiles(absolute, relative, out);
      continue;
    }
    const posixRelative = relative.split(path.sep).join('/');
    if (shouldSkipRelative(posixRelative)) continue;
    const ext = path.extname(entry.name).toLowerCase();
    if (!SCANNABLE_EXTENSIONS.has(ext)) continue;
    out.push({ absolute, relative: posixRelative });
  }
}

export function scanTree(root, scanRoots = DEFAULT_SCAN_ROOTS) {
  /** @type {Array<{ file: string, pattern: string, key: string, comment: string }>} */
  const hits = [];
  const files = [];
  for (const scanRoot of scanRoots) {
    collectFiles(path.join(root, scanRoot), scanRoot, files);
  }
  for (const file of files) {
    const source = fs.readFileSync(file.absolute, 'utf8');
    hits.push(...findEscapeHatchesInFile(file.relative, source));
  }
  for (const configFile of ROOT_CONFIG_FILES) {
    const absolute = path.join(root, configFile);
    if (!fs.existsSync(absolute)) continue;
    const reason = shouldSkipRelative(configFile);
    if (reason) continue;
    const source = fs.readFileSync(absolute, 'utf8');
    hits.push(...findEscapeHatchesInFile(configFile, source));
  }
  return hits;
}

export function loadBaseline(baselinePath) {
  const parsed = JSON.parse(fs.readFileSync(baselinePath, 'utf8'));
  if (!parsed || typeof parsed !== 'object' || !Array.isArray(parsed.entries)) {
    throw new Error(`Invalid baseline: ${baselinePath}`);
  }
  return parsed;
}

export function saveBaseline(baselinePath, baseline) {
  fs.mkdirSync(path.dirname(baselinePath), { recursive: true });
  fs.writeFileSync(baselinePath, `${JSON.stringify(baseline, null, 2)}\n`, 'utf8');
}

function entryIdentity(entry) {
  return `${entry.file}\0${entry.pattern}\0${entry.key}`;
}

export function checkEscapeHatches({
  root = defaultRoot,
  baselinePath = defaultBaselinePath,
  scanRoots = DEFAULT_SCAN_ROOTS,
} = {}) {
  const found = scanTree(root, scanRoots);
  const baseline = loadBaseline(baselinePath);
  const foundMap = new Map(found.map((entry) => [entryIdentity(entry), entry]));
  const baselineMap = new Map(baseline.entries.map((entry) => [entryIdentity(entry), entry]));

  const missingFromBaseline = found.filter((entry) => !baselineMap.has(entryIdentity(entry)));
  const staleBaseline = baseline.entries.filter((entry) => !foundMap.has(entryIdentity(entry)));

  if (missingFromBaseline.length || staleBaseline.length) {
    const parts = [];
    if (missingFromBaseline.length) {
      parts.push(
        `${missingFromBaseline.length} escape hatch(es) not in the baseline:\n${
          missingFromBaseline
            .map((entry) => `  - ${entry.file} [${entry.pattern}] ${entry.comment}`)
            .join('\n')
        }`,
      );
    }
    if (staleBaseline.length) {
      parts.push(
        `${staleBaseline.length} stale baseline entr${staleBaseline.length === 1 ? 'y' : 'ies'}:\n${
          staleBaseline
            .map((entry) => `  - ${entry.file} [${entry.pattern}] key=${entry.key}`)
            .join('\n')
        }`,
      );
    }
    return { ok: false, message: `${parts.join('\n\n')}\n\n${HELP_MESSAGE}`, found, baseline, missingFromBaseline, staleBaseline };
  }
  return { ok: true, message: 'Escape-hatch check passed.', found, baseline };
}

function summarizeByPattern(entries) {
  const counts = Object.fromEntries(PATTERN_ORDER.map((pattern) => [pattern, 0]));
  for (const entry of entries) {
    counts[entry.pattern] = (counts[entry.pattern] ?? 0) + 1;
  }
  return counts;
}

function runCli() {
  const updateBaseline = process.argv.includes('--update-baseline');
  const root = process.env.HERMES_ESCAPE_HATCHES_ROOT || defaultRoot;
  const baselinePath = process.env.HERMES_ESCAPE_HATCHES_BASELINE || defaultBaselinePath;
  const result = checkEscapeHatches({ root, baselinePath });

  if (updateBaseline) {
    if (result.missingFromBaseline?.length) {
      console.error(result.message);
      process.exit(1);
    }
    const trimmed = {
      version: result.baseline.version ?? 1,
      entries: result.found.map(({ file, pattern, key }) => ({ file, pattern, key })),
    };
    saveBaseline(baselinePath, trimmed);
    console.log(`Updated baseline (stale rows removed): ${baselinePath}`);
    console.log(JSON.stringify(summarizeByPattern(trimmed.entries), null, 2));
    process.exit(0);
  }

  if (!result.ok) {
    console.error(result.message);
    process.exit(1);
  }
  console.log(result.message);
  console.log(JSON.stringify(summarizeByPattern(result.found), null, 2));
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === path.resolve(fileURLToPath(import.meta.url));
if (isMain) runCli();