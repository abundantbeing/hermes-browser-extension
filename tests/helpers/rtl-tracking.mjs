// Which rules track their letters or force capitals, and the right-to-left
// override that switches both off. Arabic (and other joined scripts) break when
// letters are spaced apart, and capitals mean nothing in them. The override block
// at the end of extension/sidepanel.css is generated from this list, and
// tests/rtl-typography.test.mjs fails when a rule is added without it.

const SKIP_AT = /^@(keyframes|font-face|-webkit-keyframes|property|counter-style)/;

function stripComments(css) {
  return css.replace(/\/\*[\s\S]*?\*\//g, '');
}

function parseBlock(text, out) {
  let i = 0;
  while (i < text.length) {
    const open = text.indexOf('{', i);
    if (open < 0) break;
    const head = text.slice(i, open).trim();
    let depth = 1;
    let j = open + 1;
    while (j < text.length && depth > 0) {
      if (text[j] === '{') depth += 1;
      else if (text[j] === '}') depth -= 1;
      j += 1;
    }
    const body = text.slice(open + 1, j - 1);
    if (head.startsWith('@')) {
      if (!SKIP_AT.test(head)) parseBlock(body, out);
    } else if (head) {
      out.push({ selectors: splitSelectors(head), body });
    }
    i = j;
  }
}

// Split on top-level commas (not inside parentheses or brackets).
function splitSelectors(head) {
  const parts = [];
  let depth = 0;
  let current = '';
  for (const char of head) {
    if (char === '(' || char === '[') depth += 1;
    if (char === ')' || char === ']') depth -= 1;
    if (char === ',' && depth === 0) { parts.push(current); current = ''; } else current += char;
  }
  parts.push(current);
  return parts.map((part) => part.replace(/\s+/g, ' ').trim()).filter(Boolean);
}

export function trackedSelectors(cssTexts) {
  const set = new Set();
  for (const css of cssTexts) {
    const rules = [];
    parseBlock(stripComments(css).replace(/\r\n/g, '\n'), rules);
    for (const rule of rules) {
      const spacing = /letter-spacing:\s*([^;}]+)/.exec(rule.body)?.[1]?.trim();
      const tracked = spacing && !/^(0|0px|0em|normal|initial|inherit|unset)$/.test(spacing);
      const capitals = /text-transform:\s*uppercase/.test(rule.body);
      if (!tracked && !capitals) continue;
      for (const selector of rule.selectors) {
        if (/^(\d|from$|to$)/.test(selector)) continue;
        set.add(selector);
      }
    }
  }
  return [...set].sort();
}

// The same selector, only for a right-to-left document.
export function rtlSelector(selector) {
  if (/^html\b/.test(selector)) return selector.replace(/^html/, 'html[dir="rtl"]');
  if (/^:root\b/.test(selector)) return selector.replace(/^:root/, ':root[dir="rtl"]');
  return `html[dir="rtl"] ${selector}`;
}

export const RTL_DECLARATIONS = 'letter-spacing: 0 !important;\n  text-transform: none !important;';

// Plain selectors go in one list; each selector with a pseudo-element gets its own
// rule, so one the browser does not know cannot drop the others.
export function buildRtlBlock(selectors) {
  const plain = selectors.filter((selector) => !selector.includes('::'));
  const pseudo = selectors.filter((selector) => selector.includes('::'));
  const rules = [];
  rules.push(`${plain.map(rtlSelector).join(',\n')} {\n  ${RTL_DECLARATIONS}\n}`);
  for (const selector of pseudo) rules.push(`${rtlSelector(selector)} {\n  ${RTL_DECLARATIONS}\n}`);
  return rules.join('\n');
}

